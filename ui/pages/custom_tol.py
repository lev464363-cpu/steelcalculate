"""Подвкладка «Свои допуски»: ручной ввод НТД — на каждый диаметр своя строка."""
from core.tolerance import custom_path, save_custom
from ui.table_editor import TableEditorPage


class CustomTolPage(TableEditorPage):
    title = "Свои допуски"
    hint = ("Допуски по своим НТД: ТУ, стандартам предприятия, договорам. Каждая строка — один "
            "диаметр. Сохранённые НТД появляются в списках «Допуски и волоки» и «Журнал фильер». "
            "Данные — в файле dopuski.json рядом с программой.")
    COLUMNS = [("ntd", "НТД (название)", "text"), ("d", "Диаметр, мм", "num"),
               ("upper", "Верхнее отклонение, мм", "num"),
               ("lower", "Нижнее отклонение, мм", "num"), ("note", "Примечание", "note")]
    COPY_CLEAR = "d"
    COPY_TIP = "Та же НТД и отклонения — останется поменять диаметр."
    NOTE_PLACEHOLDER = ("Например: пункт ТУ, условия поставки, овальность, согласование с "
                        "потребителем…")
    FOOTNOTE = ("Отклонения — в миллиметрах со знаком: для проволоки «в минус» верхнее 0, нижнее "
                "−0,09. Можно писать через запятую. Двойной щелчок по ячейке — правка. Допуск "
                "берётся только для диаметра, который есть в таблице.")

    def path(self):
        return custom_path()

    def save_rows(self, rows):
        return save_custom(rows)

    def saved_text(self, saved):
        n = len({r["ntd"] for r in saved})
        return f"Сохранено строк: {len(saved)}, НТД: {n}. Они уже есть в списках допусков."
